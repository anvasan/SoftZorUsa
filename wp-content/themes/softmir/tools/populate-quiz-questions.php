echo "=== Populating Quiz Questions ===\n\n";

$terms = get_terms([
    'taxonomy' => 'software_category',
    'hide_empty' => false,
]);

if (is_wp_error($terms) || empty($terms)) {
    die("No terms found.\n");
}

$updated = 0;
$skipped = 0;
$not_found = 0;

foreach ($terms as $term) {
    $slug = $term->slug;

    if (!isset($quiz_map[$slug])) {
        echo "⚠️  [{$term->term_id}] {$term->name} — slug '{$slug}' not in map\n";
        $not_found++;
        continue;
    }

    $questions = $quiz_map[$slug];
    $json = wp_json_encode($questions, JSON_UNESCAPED_UNICODE);

    // Update ACF field
    $result = update_field('quiz_questions', $json, 'software_category_' . $term->term_id);

    if ($result) {
        echo "✅  [{$term->term_id}] {$term->name} — " . count($questions) . " вопросов\n";
        $updated++;
    } else {
        // Try direct meta update as fallback
        update_term_meta($term->term_id, 'quiz_questions', $json);
        echo "✅  [{$term->term_id}] {$term->name} — " . count($questions) . " вопросов (meta fallback)\n";
        $updated++;
    }
}

echo "\n=== Done ===\n";
echo "Updated: {$updated} | Skipped: {$skipped} | Not in map: {$not_found}\n";
