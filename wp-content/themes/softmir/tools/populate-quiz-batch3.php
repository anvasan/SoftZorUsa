$updated = 0;
$not_found = 0;
$already = 0;

foreach ($terms as $term) {
    $existing = get_field('quiz_questions', 'software_category_' . $term->term_id);
    if (!empty($existing)) {
        $already++;
        continue;
    }

    $slug = $term->slug;
    if (!isset($quiz_map[$slug])) {
        echo "⚠️  [{$term->term_id}] {$term->name} (slug: {$slug})\n";
        $not_found++;
        continue;
    }

    $json = wp_json_encode($quiz_map[$slug], JSON_UNESCAPED_UNICODE);
    update_field('quiz_questions', $json, 'software_category_' . $term->term_id);
    if (!get_field('quiz_questions', 'software_category_' . $term->term_id)) {
        update_term_meta($term->term_id, 'quiz_questions', $json);
    }
    echo "✅  [{$term->term_id}] {$term->name}\n";
    $updated++;
}

