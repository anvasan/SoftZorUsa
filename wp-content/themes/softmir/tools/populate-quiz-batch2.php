$terms = get_terms(['taxonomy' => 'software_category', 'hide_empty' => false]);
if (is_wp_error($terms) || empty($terms))
    die("No terms.\n");

$updated = 0;
$not_found = 0;
$already = 0;

foreach ($terms as $term) {
    $slug = $term->slug;

    // Skip if already has quiz questions
    $existing = get_field('quiz_questions', 'software_category_' . $term->term_id);
    if (!empty($existing)) {
        $already++;
        continue;
    }

    if (!isset($quiz_map[$slug])) {
        echo "⚠️  [{$term->term_id}] {$term->name} — not in batch 2 map\n";
        $not_found++;
        continue;
    }

    $questions = $quiz_map[$slug];
    $json = wp_json_encode($questions, JSON_UNESCAPED_UNICODE);

    update_field('quiz_questions', $json, 'software_category_' . $term->term_id);
    if (!get_field('quiz_questions', 'software_category_' . $term->term_id)) {
        update_term_meta($term->term_id, 'quiz_questions', $json);
    }
    echo "✅  [{$term->term_id}] {$term->name} — " . count($questions) . " вопросов\n";
    $updated++;
}

echo "\n=== Done ===\n";
